"""core/poc_exporter.py — Export Reproducible Postman Collection v2.1.0 for Confirmed Findings.

Tự động chuyển đổi các lỗ hổng đã được xác nhận runtime thành bộ sưu tập Postman Collection chuẩn,
giúp Developer/QA chỉ cần click "Import" vào Postman là có sẵn toàn bộ request để tái hiện lỗi ngay lập tức.
"""

from __future__ import annotations

import json
import urllib.parse
import uuid
from pathlib import Path
from typing import Any


def export_postman_poc_collection(
    findings: list[dict[str, Any]],
    target_name: str = "API_Target",
    out_file: str | Path = "results/poc_collection.json",
) -> Path:
    """Xuất danh sách findings sang định dạng Postman Collection v2.1.0."""
    out_path = Path(out_file)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    items: list[dict[str, Any]] = []

    for idx, f in enumerate(findings, start=1):
        vuln = f.get("vuln_type") or f.get("vulnerability") or "Security Finding"
        sev = str(f.get("severity", "medium")).upper()
        method = str(f.get("method", "GET")).upper()
        ep = str(f.get("endpoint", "/"))

        repro = f.get("reproduction") or {}
        curl_cmd = f.get("reproduction_curl") or repro.get("curl") or ""
        evidence = str(f.get("evidence", ""))
        cwe = str(f.get("cwe", ""))
        owasp = str(f.get("owasp_category", ""))

        target_url = repro.get("url") or f.get("url") or f"http://localhost{ep}"
        parsed_url = urllib.parse.urlparse(target_url)

        headers_list: list[dict[str, str]] = []
        raw_headers = repro.get("headers") or {}
        for h_k, h_v in raw_headers.items():
            headers_list.append({"key": str(h_k), "value": str(h_v), "type": "text"})

        # Xử lý body nếu có
        body_obj: dict[str, Any] = {"mode": "raw", "raw": ""}
        if "tampered_payload" in repro:
            body_obj["raw"] = json.dumps(repro["tampered_payload"], ensure_ascii=False, indent=2)
            body_obj["options"] = {"raw": {"language": "json"}}
        elif "json_body" in repro or "body" in repro:
            b_data = repro.get("json_body") or repro.get("body")
            body_obj["raw"] = json.dumps(b_data, ensure_ascii=False, indent=2) if isinstance(b_data, (dict, list)) else str(b_data)
            body_obj["options"] = {"raw": {"language": "json"}}
        elif "query" in repro:  # Cho GraphQL
            body_obj["raw"] = json.dumps({"query": repro["query"]}, ensure_ascii=False, indent=2)
            body_obj["options"] = {"raw": {"language": "json"}}

        desc = (
            f"### Vulnerability: {vuln}\n"
            f"- **Severity**: {sev}\n"
            f"- **CWE**: {cwe}\n"
            f"- **OWASP**: {owasp}\n"
            f"- **Evidence**: {evidence}\n\n"
            f"#### 1-Click cURL Reproduce:\n```bash\n{curl_cmd}\n```"
        )

        item_entry: dict[str, Any] = {
            "name": f"[{sev}] [{method}] {ep} - {vuln}",
            "request": {
                "method": method,
                "header": headers_list,
                "url": {
                    "raw": target_url,
                    "protocol": parsed_url.scheme or "http",
                    "host": [parsed_url.hostname or "localhost"],
                    "port": str(parsed_url.port) if parsed_url.port else "",
                    "path": [p for p in parsed_url.path.strip("/").split("/") if p],
                },
                "description": desc,
            },
        }

        if body_obj["raw"]:
            item_entry["request"]["body"] = body_obj

        items.append(item_entry)

    collection_data = {
        "info": {
            "_postman_id": str(uuid.uuid4()),
            "name": f"PoC Collection — {target_name}",
            "description": f"Automated 1-Click Vulnerability Reproduction Collection generated by LLM-Assisted API Fuzzer for {target_name}.",
            "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
        },
        "item": items,
    }

    out_path.write_text(json.dumps(collection_data, ensure_ascii=False, indent=2), encoding="utf-8")
    return out_path
